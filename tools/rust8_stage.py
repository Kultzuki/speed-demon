"""Freeze the measured Rust finalists; preserve every replaced C++ source."""
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[1]
def digest(path): return hashlib.sha256(path.read_bytes()).hexdigest()

selection_path = ROOT / 'research/rust8-selection.json'
assert not selection_path.exists()
incoming = json.loads((ROOT / 'validation/rust8-incoming-sources.json').read_text())
assert subprocess.check_output(['git', 'rev-parse', 'HEAD'], text=True).strip() == 'e9deec07fa38f9abf0c167d6768c41c388e37ba5'
for file in ['main.rs', 'common.rs']:
    shutil.copy2(ROOT / f'research/prototypes/d-simple8/{file}', ROOT / f'track-d/{file}')
selection = {'created_at': datetime.now(timezone.utc).isoformat(),
    'starting_commit': 'e9deec07fa38f9abf0c167d6768c41c388e37ba5',
    'status': 'Frozen for complete validation and official measurement; no claimed official improvement yet',
    'user_original_d_sha256': incoming['user_d_sha256'], 'selected': {}}
for track in 'ad':
    folder = ROOT / f'track-{track}'
    for file in ['main.cpp', 'common.hpp', 'Dockerfile', '.speed-demon.toml']:
        assert digest(folder / file) == incoming[f'track-{track}/{file}'], (track, file)
        assert digest(ROOT / f'research/baseline8/track-{track}/{file}') == incoming[f'track-{track}/{file}']
    (folder / 'main.cpp').unlink()
    (folder / 'common.hpp').unlink()
    shutil.copy2(ROOT / 'research/prototypes/rust8.Dockerfile', folder / 'Dockerfile')
    (folder / '.speed-demon.toml').write_text(f'track = "{track}"\nteam = "CodeScythe"\nlanguage = "Rust"\ndependency_count = 0\n')
    (folder / 'Cargo.toml').write_text('[package]\nname = "solution"\nversion = "0.1.0"\nedition = "2021"\n\n[[bin]]\nname = "solution"\npath = "main.rs"\n\n[dependencies]\n')
    (folder / 'Cargo.lock').write_text('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "solution"\nversion = "0.1.0"\n')
    selection['selected'][track] = {'sources': {f: digest(folder / f) for f in ['main.rs', 'common.rs']},
        'S': 449 if track == 'a' else 485, 'D': 1,
        'source_origin': 'buffered scalar parser' if track == 'a' else 'research/prototypes/d-simple8',
        'previous_cpp': f'research/baseline8/track-{track}'}
with selection_path.open('x') as stream:
    json.dump(selection, stream, indent=2); stream.write('\n')
with (ROOT / 'research/HANDOVER_INCOMING_RUST8.md').open('xb') as stream:
    stream.write((ROOT / '.out/continuation8-rust-incoming/files/HANDOVER_NEXT.md').read_bytes())
print('Frozen Rust A and D. Exact prior C++ and original user D are preserved.')
